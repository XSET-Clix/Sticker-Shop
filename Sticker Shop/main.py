import cv2
import numpy as np
photo=np.full((256,512,3),(200,210,220),np.uint8)
cv2.circle(photo,(256,150),80,(40,40,200),-1)
cv2.ellipse(photo,(300,58),(30,14),-30,0,360,(60,170,60),-1)
cv2.rectangle(photo,(420,30),(500,110),(150,110,70),-1)
clicks=[(256,150,1),(460,60,0)]
guesses=np.full((3,256,256),-4.0,np.float32)
cv2.ellipse(guesses[0],(128,150),(40,80),0,0,360,4.0,-1)
cv2.ellipse(guesses[1],(128,150),(10,20),0,0,360,4.0,-1)
cv2.ellipse(guesses[2],(128,150),(40,80),0,0,360,4.0,-1)
cv2.ellipse(guesses[2],(150,58),(15,14),-30,0,360,4.0,-1)
print("Photo",photo.shape,"guesses",guesses.shape)
print("\nPART 1: Prompts for SAM")
points=np.array([[x*2,y*4] for x,y,_ in clicks],dtype=np.float32)
labels=np.array([label for _,_,label in clicks],dtype=np.int64)
print(points.tolist())
print(labels.tolist())
print("points shape",points[None,None,:].shape,"labels shape",labels[None,None,:].shape)
print("\nPART 2: Part, bigger, whole")
ordered=sorted(range(3),key=lambda i:int(np.sum(guesses[i]>0)))
sizes=[int(np.sum(guesses[i]>0)) for i in ordered]
print(sizes)
print("\nPART 3: Mask")
biggest=ordered[-1]
resized=cv2.resize(guesses[biggest],(512,256),interpolation=cv2.INTER_LINEAR)
mask=(resized>0).astype(np.uint8)
print(mask.shape,int(np.sum(mask)))
print("\nPART 4: Sticker")
coords=cv2.findNonZero(mask)
x,y,w,h=cv2.boundingRect(coords)
box=(x,y,x+w,y+h)
blurred=cv2.blur(mask,(3,3))
alpha=np.where(blurred>=0.5,255,0).astype(np.uint8)
rgba=np.concatenate((photo,alpha[:,:,None]),axis=2)
sticker=rgba[y:y+h,x:x+w].copy()
middle=(sticker.shape[1]//2,sticker.shape[0]//2)
top_left=(0,0)
print(box,sticker.shape)
print("middle alpha",sticker[middle[1],middle[0],3])
print("top-left alpha",sticker[top_left[1],top_left[0],3])
cv2.imwrite("sticker.png",sticker)
